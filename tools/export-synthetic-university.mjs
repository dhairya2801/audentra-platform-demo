#!/usr/bin/env node
/**
 * Materialises the synthetic university as an integrity-checked asset the
 * Python seeder can read without a JavaScript runtime.
 *
 * The generator is the source of truth for the population; this script is the
 * bridge. It generates, validates, and writes two files:
 *
 *   apps/api/assets/demo/synthetic-university-v1.json.gz
 *   apps/api/src/audentra/infrastructure/seeding/synthetic_university_asset.py
 *
 * The second pins the first: the seeder refuses to import an archive whose
 * SHA-256 does not match the constant. Regenerating is a two-file change, so a
 * hand-edited archive fails the import rather than silently redefining the
 * demo population.
 *
 * Determinism is the whole point. Same seed, same student count, same
 * reference instant produce byte-identical output, so the digest below is a
 * property of the generator source rather than of the run.
 *
 *   node tools/export-synthetic-university.mjs [--seed N] [--students N]
 */

import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { gzipCanonicalJson } from "./demo-api/src/synthetic-university/archive.js";
import {
  DEFAULT_NOW,
  DEFAULT_SEED,
  DEFAULT_STUDENT_COUNT,
  UNIVERSE_VERSION,
  generateUniverse,
  validateUniverse,
} from "./demo-api/src/synthetic-university/index.js";

const REPOSITORY_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ARCHIVE_PATH = join(
  REPOSITORY_ROOT,
  "apps/api/assets/demo/synthetic-university-v1.json.gz",
);
const CONSTANTS_PATH = join(
  REPOSITORY_ROOT,
  "apps/api/src/audentra/infrastructure/seeding/synthetic_university_asset.py",
);

/** Collections the Python importer reads. Counting them pins the shape too. */
const COUNTED_COLLECTIONS = [
  "students",
  "applications",
  "checklistTasks",
  "documents",
  "holds",
  "fafsaRecords",
  "verificationRequirements",
  "aidAwards",
  "disbursements",
  "sapStatus",
  "accountLedger",
  "housingApplications",
  "housingAssignments",
  "orientationRegistrations",
  "registrationEligibility",
  "internationalRequirements",
  "terms",
  "programs",
  "advisors",
  "residenceHalls",
  "mealPlans",
  "holdTypes",
  "documentCategories",
  "awardFunds",
  "orientationSessions",
  "costOfAttendance",
  "checklistTaskCatalogue",
  "personas",
];

function parseArguments(argv) {
  const options = { seed: DEFAULT_SEED, studentCount: DEFAULT_STUDENT_COUNT };
  for (let index = 0; index < argv.length; index += 1) {
    const flag = argv[index];
    if (flag === "--seed" || flag === "--students") {
      const raw = argv[index + 1];
      const value = Number.parseInt(raw ?? "", 10);
      if (!Number.isInteger(value)) {
        throw new Error(`${flag} requires an integer; received ${raw ?? "nothing"}`);
      }
      if (flag === "--seed") options.seed = value;
      else options.studentCount = value;
      index += 1;
      continue;
    }
    throw new Error(`Unknown flag ${flag}`);
  }
  return options;
}

function pythonInteger(value) {
  return String(value);
}

function pythonString(value) {
  return JSON.stringify(String(value));
}

function renderConstants({ digest, seed, studentCount, counts, archiveBytes }) {
  const countLines = COUNTED_COLLECTIONS.map(
    (name) => `        ${pythonString(name)}: ${pythonInteger(counts[name])},`,
  ).join("\n");
  return `"""Integrity constants for the packaged synthetic-university archive.

Generated by \`node tools/export-synthetic-university.mjs\`. Do not edit by
hand: the digest is what lets the seeder trust the archive, and a mismatch
between this file and the archive is exactly the condition it exists to catch.
"""

from __future__ import annotations

from collections.abc import Mapping
from types import MappingProxyType
from typing import Final

#: Repository-relative location of the gzip-compressed universe.
ASSET_RELATIVE_PATH: Final = "demo/synthetic-university-v1.json.gz"

#: SHA-256 of the *compressed* archive exactly as written to disk.
ASSET_SHA256: Final = ${pythonString(digest)}

#: Byte length of the compressed archive.
ASSET_SIZE_BYTES: Final = ${pythonInteger(archiveBytes)}

#: \`meta.version\` the archive must declare.
UNIVERSE_VERSION: Final = ${pythonString(UNIVERSE_VERSION)}

#: Generator inputs that produced the archive.
UNIVERSE_SEED: Final = ${pythonInteger(seed)}
UNIVERSE_STUDENT_COUNT: Final = ${pythonInteger(studentCount)}
UNIVERSE_GENERATED_FOR: Final = ${pythonString(DEFAULT_NOW)}

#: Row counts per collection, asserted after decoding.
UNIVERSE_COLLECTION_COUNTS: Final[Mapping[str, int]] = MappingProxyType(
    {
${countLines}
    }
)
`;
}

async function main() {
  const { seed, studentCount } = parseArguments(process.argv.slice(2));

  const generationStarted = performance.now();
  const universe = generateUniverse({ seed, studentCount, now: DEFAULT_NOW });
  const generationMs = performance.now() - generationStarted;

  const validationStarted = performance.now();
  const violations = validateUniverse(universe);
  const validationMs = performance.now() - validationStarted;
  if (violations.length > 0) {
    console.error(`The generated universe violates ${violations.length} invariant(s):`);
    for (const violation of violations.slice(0, 25)) console.error(`  - ${violation}`);
    if (violations.length > 25) console.error(`  … and ${violations.length - 25} more`);
    process.exitCode = 1;
    return;
  }

  const counts = {};
  for (const name of COUNTED_COLLECTIONS) {
    const collection = universe[name];
    if (!Array.isArray(collection)) {
      throw new Error(`Universe collection ${name} is missing or is not an array`);
    }
    counts[name] = collection.length;
  }

  // Level 9 keeps the checked-in archive small; the digest covers the exact
  // bytes, so the compression level is part of the reproducible output.
  const archive = gzipCanonicalJson(universe);
  const digest = createHash("sha256").update(archive).digest("hex");

  await mkdir(dirname(ARCHIVE_PATH), { recursive: true });
  await writeFile(ARCHIVE_PATH, archive);
  await writeFile(
    CONSTANTS_PATH,
    renderConstants({ digest, seed, studentCount, counts, archiveBytes: archive.length }),
    "utf8",
  );

  console.log(`seed                ${seed}`);
  console.log(`students            ${studentCount}`);
  console.log(`reference instant   ${DEFAULT_NOW}`);
  console.log(`generation          ${generationMs.toFixed(0)} ms`);
  console.log(`validation          ${validationMs.toFixed(0)} ms (0 violations)`);
  console.log(`archive             ${(archive.length / 1_048_576).toFixed(2)} MiB`);
  console.log(`sha256              ${digest}`);
  console.log(`wrote               ${ARCHIVE_PATH}`);
  console.log(`wrote               ${CONSTANTS_PATH}`);
}

await main();
