#!/usr/bin/env node
/**
 * Paraphrase the development bank so the suite measures the pipeline, not
 * the exact wording the bank was tuned on.
 *
 * For every single-turn case, a model writes two rewordings a real student
 * or staff member would type (different vocabulary, contractions, typos
 * allowed, same meaning, same named people). Expectations are inherited
 * unchanged, so a paraphrase that changes the meaning shows up as a failure
 * to read, which is the point. Output: paraphrase-cases.mjs (committed, so a
 * run is reproducible without re-spending).
 *
 *   OPENAI_API_KEY=… node tools/edward-eval/knowledge/paraphrase.mjs [--model gpt-5.6-luna]
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CASES } from "./cases.mjs";
import { priceUsd } from "../src/pricing.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const MODEL = args.includes("--model") ? args[args.indexOf("--model") + 1] : "gpt-5.6-luna";
const API_KEY = process.env.OPENAI_API_KEY;
if (!API_KEY) {
  console.error("OPENAI_API_KEY is required");
  process.exit(2);
}

const SCHEMA = {
  type: "json_schema",
  json_schema: {
    name: "paraphrases",
    strict: true,
    schema: {
      type: "object",
      properties: {
        paraphrases: { type: "array", items: { type: "string" }, minItems: 2, maxItems: 2 },
      },
      required: ["paraphrases"],
      additionalProperties: false,
    },
  },
};

let spend = 0;
async function paraphrase(question, actorKind) {
  const body = {
    model: MODEL,
    reasoning_effort: "none",
    max_completion_tokens: 300,
    response_format: SCHEMA,
    messages: [
      {
        role: "system",
        content:
          `Rewrite the question below as two different messages a ${actorKind === "student" ? "university student" : "university staff member"} might type into an assistant chat. ` +
          "Keep the exact meaning and every named person, office, program, amount and date. Vary vocabulary and sentence shape " +
          "(one casual with lowercase or a small typo, one more formal). Do not answer the question. Do not add new facts.",
      },
      { role: "user", content: question },
    ],
  };
  const response = await fetch("https://api.openai.com/v1/chat/completions", {
    method: "POST",
    headers: { "content-type": "application/json", authorization: `Bearer ${API_KEY}` },
    body: JSON.stringify(body),
  });
  const payload = await response.json();
  if (!response.ok) throw new Error(JSON.stringify(payload).slice(0, 300));
  const usage = payload.usage ?? {};
  spend += priceUsd(MODEL, usage.prompt_tokens, usage.completion_tokens);
  return JSON.parse(payload.choices[0].message.content).paraphrases;
}

const out = [];
for (const testCase of CASES) {
  if (testCase.turns.length !== 1) continue;
  const variants = await paraphrase(testCase.turns[0].question, testCase.actorKind);
  variants.forEach((question, index) => {
    out.push({
      ...testCase,
      id: `kp-${testCase.id.replace(/^kn-/, "")}-${index + 1}`,
      category: testCase.category,
      turns: [{ question, expect: testCase.turns[0].expect }],
      paraphraseOf: testCase.id,
    });
  });
  process.stderr.write(`  ${testCase.id}: ${variants.map((v) => JSON.stringify(v)).join(" | ")}\n`);
}

const file = join(HERE, "paraphrase-cases.mjs");
writeFileSync(
  file,
  `/**\n * GENERATED by paraphrase.mjs (${MODEL}, ${new Date().toISOString()}) — do not edit.\n * Two rewordings of every single-turn development case; expectations inherited.\n */\n\nexport const PARAPHRASE_CASES = ${JSON.stringify(out, null, 2)};\n`,
);
console.error(`wrote ${out.length} paraphrase cases to ${file}; paraphrase spend $${spend.toFixed(4)}`);
